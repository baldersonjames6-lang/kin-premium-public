def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def write_sums(bdir):
    bdir = Path(bdir)
    files = ["manifest.json", "episodes.jsonl"] + sorted(
        str(p.relative_to(bdir)) for p in (bdir / "events").glob("*.jsonl"))
    lines = [f"{sha256(bdir / f)}  {f}" for f in files if (bdir / f).exists()]
    (bdir / "SHA256SUMS").write_text("\n".join(lines) + "\n")


